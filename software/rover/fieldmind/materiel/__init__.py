"""Pilotes du matériel du rover, et interface commune au matériel réel et simulé."""

from __future__ import annotations

from typing import Any, Protocol

from fieldmind.materiel.esp import PiloteEsp


class Materiel(Protocol):
    """Ce que le reste du logiciel attend du matériel (réel : detection.py, ou simulation)."""

    nom: str  # "reel" | "simulation"

    def demarrer(self) -> None: ...
    def arreter(self) -> None: ...
    def esp(self) -> PiloteEsp | None: ...
    def capteurs(self) -> dict[str, Any]:
        """Champ `capteurs` du message `etat` : lidar, gauche, droite, gnss, esp, micro."""
        ...
    def systeme(self) -> dict[str, Any]: ...
    def inventaire(self) -> dict[str, Any]:
        """Appareils détectés (USB, ports série, caméras) pour le menu Système."""
        ...
    def lidar_marche(self, marche: bool) -> bool: ...
    def micro_actif(self, actif: bool) -> bool: ...
    def cameras_inversees(self, inverse: bool) -> None: ...
